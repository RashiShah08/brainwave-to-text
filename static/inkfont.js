/** Fallback for anything unmapped: an empty quad, as a compositor would set. */
const TOFU = [[[0.06, 0], [0.56, 0], [0.56, 1], [0.06, 1], [0.06, 0]]];

/**
 * Flattened segments for one character.
 * Returns `{segments, advance}` where each segment is
 * `[x1, y1, x2, y2, atFraction]` — `atFraction` being how far through the
 * character's total pen travel that segment sits, in 0..1.
 */
export function strokes(ch) {
  const key = String(ch || '').toUpperCase();
  if (key === ' ') return { segments: [], advance: SPACE };
  const polys = F[key] || TOFU;

  const flat = [];
  let total = 0;
  for (const poly of polys) {
    for (let i = 0; i < poly.length - 1; i++) {
      const [x1, y1] = poly[i];
      const [x2, y2] = poly[i + 1];
      const len = Math.hypot(x2 - x1, y2 - y1);
      flat.push([x1, y1, x2, y2, len]);
      total += len;
    }
  }
  let run = 0;
  for (const seg of flat) {
    run += seg[4];
    seg[4] = total > 0 ? run / total : 1;
  }
  return { segments: flat, advance: ADVANCE };
}

/** Widest a glyph gets, for layout that must reserve space up front. */
